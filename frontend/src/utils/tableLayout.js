/**
 * 管理后台列表：列宽与列规范单一真相源（2026-08-20 统一）。
 *
 * 【解决什么】改造前 11 个列表页各写各的宽度，同语义列宽度不一——实测：
 *   「操作」7 种（120/150/160/180/200/280/300）、「状态」3 种（90/100/110）、
 *   「名称」3 种（150/160/200）、「提交时间」2 种。页面间横向扫读时列对不成竖线，
 *   且新增页面只能靠"抄旁边那页"，偏差会持续累积。
 *
 * 【为什么是 JS 常量而不只是 CSS 变量】Element 的 `width` / `min-width` 要的是数值，
 * 传 `var(--col-status)` 不生效。故列宽以本文件为准（模板 `:width="COL.STATUS"`），
 * `theme.css` 里同名 CSS 变量取同值，供样式侧（占位框、min-width）引用——两处同源同值。
 *
 * 【宽度怎么定的】按内容实测推导，非拍脑袋：
 *   TIME  = "2026-08-20 17:35"（16 字符）× 等宽数字 + 单元格 padding；
 *   STATUS= 最长状态文案「部分已上架」5 字 + 徽标 padding；
 *   COUNT = 4 位数字居中；TAG = 最长「streamable-http」按标签缩略后的宽度。
 *
 * 【操作列】按钮数分挡定宽（产品口径：全部平铺，不收进「更多」下拉——
 * 一眼看尽所有操作、少点一次）。挡位取值 = 按钮文字宽 + 分隔线 + flex gap 实测值。
 */

/**
 * 列宽（px）。与 theme.css 的 --col-* 变量同源同值。
 *
 * 【2026-08-22 按实测重分配】原值为估算，实测（1920px 无溢出态下用 canvas 量文字真实像素）
 * 发现普遍超配：计数列表头最长 53px 却给 88、状态列值最长 42px 却给 96。
 * 超配本身不是错，但 10 列的页面（岗位）因此累计 1418px，1600px 宽屏都放不下、
 * 右侧固定操作列会压住状态列。故按「max(表头文字, 最长值) + 24 padding」收敛，
 * 并对每列留出至少 20px 余量应对更长的数据。
 */
export const COL = {
  /** 状态徽标列。实测最长值「已发布」42px + 徽标 padding */
  STATUS: 84,
  /** 时间戳列（等宽数字，定宽保证各行对齐）。实测 "2026-08-21 15:40" = 122px */
  TIME: 152,
  /** 用户名 / 提交人 / 上传用户 */
  USER: 132,
  /** 纯数字列（工具数 / 被引用 / 上下文 / 技能数），配 align="center"。
   *  实测最长表头「Agent数」53px —— 本列瓶颈是表头而非值（值最长仅 13px） */
  COUNT: 80,
  /** 单标签列（类别 / 传输 / 来源 / 用途）。
   *  注意：表头超过 6 个中文字的列（如「最近发布版本」84px）不适用本值，
   *  应另给定宽或缩短表头，否则表头会换行 */
  TAG: 104,
  /** 名称主列最小宽（用 min-width，不定宽——主列吃剩余空间） */
  NAME_MIN: 180,
  /** 描述列最小宽（用 min-width，务必配 show-overflow-tooltip） */
  DESC_MIN: 240
}

/**
 * 操作列宽度分挡（px）：按该页操作区**最多**同时出现几个按钮取挡。
 *
 * <p>分挡而非逐页定值的理由：逐页精算会再次退化成"7 种宽度"，分挡才能让
 * 按钮数相同的页面宽度一致。挡与挡之间差 52px ≈ 一个双字按钮 + 分隔线 + gap。</p>
 *
 * <p>【2026-08-22 按实测收窄】原挡位（140/200/260/320）实测富余 53–173px：
 * 岗位页 3 按钮内容仅 147px 却占 320px（用了 5 挡）。富余在窄页无害，
 * 但在 8–10 列的页面里直接把表格顶出视口。现挡位在实测内容宽上留 ~30–40px 余量。</p>
 */
export const OPS_W = {
  /** 1–2 个按钮（如：编辑 / 删除）。实测 2 按钮内容约 96px */
  2: 124,
  /** 3 个按钮。实测「编辑/版本发布/停用」内容 147px */
  3: 176,
  /** 4 个按钮。实测「查看/编辑/停用/设为默认」内容 187px */
  4: 228,
  /** 5 个按钮（当前上限：查看/编辑/发布/设为默认/删除） */
  5: 280
}

/**
 * 取操作列宽度：按钮数 → 挡位宽度。
 *
 * @param {number} maxButtons 该页操作区最多同时出现的按钮数
 * @returns {number} 列宽 px
 */
export function opsWidth(maxButtons) {
  const n = Math.max(2, Math.min(5, Number(maxButtons) || 2))
  return OPS_W[n]
}

/** 空值占位符：全站统一用它，不要各页再写裸 '—' 或 '-'。 */
export const NA = '—'
